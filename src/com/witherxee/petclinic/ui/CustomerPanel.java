    private void tblCustomersMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblCustomersMouseClicked

        int row = tblCustomers.getSelectedRow();

        if (row >= 0) {
            selectedCustomerId = Integer.parseInt(
                    tblCustomers.getValueAt(row, 0).toString());

            txtName1.setText(
                    tblCustomers.getValueAt(row, 1).toString());

            txtPhone1.setText(
                    tblCustomers.getValueAt(row, 2).toString());

            txtEmail1.setText(
                    tblCustomers.getValueAt(row, 3).toString());

            txtAddress1.setText(
                    tblCustomers.getValueAt(row, 4).toString());
        }
    }//GEN-LAST:event_tblCustomersMouseClicked


