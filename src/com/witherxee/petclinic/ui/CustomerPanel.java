    private void btnAdd1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed

        if (!validateFields()) {
            return;
        }

        Customer customer = new Customer(
                0,
                txtName1.getText().trim(),
                txtPhone1.getText().trim(),
                txtEmail1.getText().trim(),
                txtAddress1.getText().trim()
        );

        controller.addCustomer(customer);
        loadCustomers();
        clearFields();

        JOptionPane.showMessageDialog(
                this,
                "Customer added successfully.",
                "Success",
                JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdate1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed

        if (selectedCustomerId == -1) {
            JOptionPane.showMessageDialog(
                    this,
                    "Please select a customer.",
                    "Validation",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (!validateFields()) {
            return;
        }

        Customer customer = new Customer(
                selectedCustomerId,
                txtName1.getText().trim(),
                txtPhone1.getText().trim(),
                txtEmail1.getText().trim(),
                txtAddress1.getText().trim()
        );

        controller.updateCustomer(customer);
        loadCustomers();
        clearFields();

        JOptionPane.showMessageDialog(
                this,
                "Customer updated successfully.",
                "Success",
                JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDelete1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed

        if (selectedCustomerId == -1) {
            JOptionPane.showMessageDialog(
                    this,
                    "Please select a customer.",
                    "Validation",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        int result = JOptionPane.showConfirmDialog(
                this,
                "Are you sure you want to delete this customer?",
                "Confirm Delete",
                JOptionPane.YES_NO_OPTION);

        if (result == JOptionPane.YES_OPTION) {
            controller.deleteCustomer(selectedCustomerId);
            loadCustomers();
            clearFields();

            JOptionPane.showMessageDialog(
                    this,
                    "Customer deleted successfully.",
                    "Success",
                    JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

